import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_app_check/firebase_app_check.dart';
import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';

import '../core/logging/app_logger.dart';
import '../firebase_options.dart';

enum FirebaseSetupStatus { ready, notConfigured, failed }

class FirebaseSetupResult {
  const FirebaseSetupResult(
    this.status, {
    this.usingEmulators = false,
    this.appCheckActive = false,
  });

  final FirebaseSetupStatus status;
  final bool usingEmulators;
  final bool appCheckActive;

  bool get isReady => status == FirebaseSetupStatus.ready;
}

/// Initialises Firebase from `lib/firebase_options.dart` (generated by
/// `flutterfire configure`).
///
/// Build-time switches (`--dart-define`):
/// * `USE_FIREBASE_EMULATOR=true` – connect to the local Emulator Suite with
///   a `demo-` project id (no real project or credentials needed).
/// * `FIREBASE_EMULATOR_HOST=<host>` – emulator host (default `localhost`,
///   `10.0.2.2` on Android emulators).
/// * `APP_CHECK=true` – activate App Check (Play Integrity / App Attest /
///   reCAPTCHA v3). Requires console setup; see README.
/// * `RECAPTCHA_SITE_KEY=<key>` – public reCAPTCHA v3 site key for web.
abstract final class FirebaseInitializer {
  static const useEmulators = bool.fromEnvironment('USE_FIREBASE_EMULATOR');
  static const _emulatorHost = String.fromEnvironment('FIREBASE_EMULATOR_HOST');
  static const _appCheck = bool.fromEnvironment('APP_CHECK');
  static const _recaptchaSiteKey = String.fromEnvironment('RECAPTCHA_SITE_KEY');

  static const demoProjectId = 'demo-daily-expense-buddy';

  static String get emulatorHost {
    if (_emulatorHost.isNotEmpty) return _emulatorHost;
    if (!kIsWeb && defaultTargetPlatform == TargetPlatform.android) {
      return '10.0.2.2';
    }
    return 'localhost';
  }

  /// Options for the emulator-only `demo-` project. Emulators accept any
  /// API key for demo projects; these values cannot reach production.
  static FirebaseOptions get _demoOptions {
    final platform = kIsWeb
        ? 'web'
        : (defaultTargetPlatform == TargetPlatform.iOS ? 'ios' : 'android');
    return FirebaseOptions(
      apiKey: 'demo-api-key',
      appId: '1:000000000000:$platform:0000000000000000',
      messagingSenderId: '000000000000',
      projectId: demoProjectId,
      iosBundleId: 'com.dailyexpensebuddy.app',
    );
  }

  static Future<FirebaseSetupResult> initialize() async {
    try {
      final options = useEmulators
          ? _demoOptions
          : DefaultFirebaseOptions.currentPlatform;
      await Firebase.initializeApp(options: options);
    } on UnsupportedError catch (e) {
      AppLogger.warn('Firebase', 'Firebase is not configured', e);
      return const FirebaseSetupResult(FirebaseSetupStatus.notConfigured);
    } catch (e, st) {
      AppLogger.error('Firebase', 'Initialisation failed', e, st);
      return const FirebaseSetupResult(FirebaseSetupStatus.failed);
    }

    // Offline persistence on mobile. On web the cache is memory-only so that
    // financial data is not left in a shared browser's storage after logout.
    FirebaseFirestore.instance.settings = Settings(persistenceEnabled: !kIsWeb);

    if (useEmulators) {
      final host = emulatorHost;
      await FirebaseAuth.instance.useAuthEmulator(host, 9099);
      FirebaseFirestore.instance.useFirestoreEmulator(host, 8080);
      AppLogger.info('Firebase', 'Using emulators at $host');
      return const FirebaseSetupResult(
        FirebaseSetupStatus.ready,
        usingEmulators: true,
      );
    }

    return FirebaseSetupResult(
      FirebaseSetupStatus.ready,
      appCheckActive: await _activateAppCheck(),
    );
  }

  static Future<bool> _activateAppCheck() async {
    if (!_appCheck) return false;
    if (kIsWeb && _recaptchaSiteKey.isEmpty) {
      AppLogger.warn(
        'AppCheck',
        'APP_CHECK set but RECAPTCHA_SITE_KEY missing',
      );
      return false;
    }
    try {
      await FirebaseAppCheck.instance.activate(
        providerWeb: kIsWeb ? ReCaptchaV3Provider(_recaptchaSiteKey) : null,
        providerAndroid: kDebugMode
            ? const AndroidDebugProvider()
            : const AndroidPlayIntegrityProvider(),
        providerApple: kDebugMode
            ? const AppleDebugProvider()
            : const AppleAppAttestWithDeviceCheckFallbackProvider(),
      );
      return true;
    } catch (e, st) {
      AppLogger.error('AppCheck', 'Activation failed', e, st);
      return false;
    }
  }

  /// Removes cached Firestore data from the device after sign-out (mobile).
  static Future<void> clearLocalCache() async {
    if (kIsWeb) return; // web uses a memory-only cache
    try {
      await FirebaseFirestore.instance.terminate();
      await FirebaseFirestore.instance.clearPersistence();
      AppLogger.info('Firebase', 'Local cache cleared');
    } catch (e) {
      AppLogger.warn('Firebase', 'Could not clear local cache', e);
    }
  }

  /// Whether local writes are still waiting to reach the server.
  static Future<bool> hasPendingWrites() async {
    try {
      await FirebaseFirestore.instance.waitForPendingWrites().timeout(
        const Duration(seconds: 3),
      );
      return false;
    } catch (_) {
      return true;
    }
  }
}
